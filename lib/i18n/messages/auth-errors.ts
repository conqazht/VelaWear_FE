export type AuthErrorMessageKey = keyof (typeof authErrorMessages)["en"];

export function getAuthValidationMessageKey(message?: string): AuthErrorMessageKey {
  switch (message) {
    case "Invalid Email":
      return "auth.validation.invalidEmail";
    case "Minimum 8 characters":
      return "auth.validation.passwordMin";
    case "Maximum 100 characters":
      return "auth.validation.passwordMax";
    case "Requires 1 uppercase letter":
      return "auth.validation.passwordUppercase";
    case "Requires 1 lowercase letter":
      return "auth.validation.passwordLowercase";
    case "Requires 1 number":
      return "auth.validation.passwordNumber";
    default:
      return "auth.validation.required";
  }
}

export function getAuthRoleMessageKey(role?: string | null): AuthErrorMessageKey {
  switch (role?.trim().toLowerCase()) {
    case "admin":
      return "auth.common.role.admin";
    case "manager":
      return "auth.common.role.manager";
    case "staff":
      return "auth.common.role.staff";
    case "user":
    case "member":
      return "auth.common.role.user";
    default:
      return "auth.common.role.account";
  }
}
